# variable-demo3

# Integer variable
age = 25

# Float variable
height = 5.9

# String variable
name = "Sarah"

# Boolean variable
is_student = True

# Print variables
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student Status:", is_student)

# Updating variables
age = age + 1
print("Updated Age:", age)

# Combining variables
message = name + " is " + str(age)
print(message)

# Multiple assignment
x, y, z = 10, 20, 30
print("x:", x, "y:", y, "z:", z)

# Swapping variables
print("After swapping x and y:")
print("x:", x, "y:", y)
